/** «12 золотых монет», «40 кредитов», «25 крышек» → 12/40/25 (деньги), иначе null. */
export const moneyIn = (item: string): number | null => {
  const m = item.match(/^(\d+)\s+(золот|кредит|крыш|шиллинг|доллар)/i);
  return m ? parseInt(m[1], 10) : null;
};
