// Оракул вариативности. Языковые модели плохо «бросают кубики» в голове: просьба
// «выбери случайно» даёт одни и те же ответы. Поэтому случайность выбирает движок,
// а модель получает готовые слоты и мотивы и превращает их в сюжет.

type Rng = () => number;
const pick = <T,>(arr: readonly T[], rng: Rng): T => arr[Math.floor(rng() * arr.length) % arr.length];

/** Пары «действие + тема» в духе Mythic GME — для неожиданных, но связных поворотов. */
const MUSE_ACTIONS = [
  'предать', 'спрятать', 'потребовать', 'освободить', 'подделать', 'защитить', 'разрушить', 'выменять', 'разоблачить', 'преследовать',
  'обещать', 'украсть', 'исцелить', 'заманить', 'вернуть', 'пробудить', 'запечатать', 'подслушать', 'спасти', 'обмануть',
  'отомстить', 'сбежать', 'пожертвовать', 'объединить', 'проклясть',
] as const;
const MUSE_SUBJECTS = [
  'долг', 'старая карта', 'ребёнок', 'клятва', 'чужое имя', 'огонь', 'ключ', 'семейная тайна', 'зверь', 'мост',
  'песня', 'письмо', 'болезнь', 'наследство', 'зеркало', 'урожай', 'призрак', 'монета', 'буря', 'забытый бог',
  'маска', 'колокол', 'свидетель', 'трон', 'тень прошлого',
] as const;

/** Мягкие мотивы для детских стилей — без угроз и мрака. */
const GENTLE_ACTIONS = ['найти', 'подарить', 'помочь', 'разгадать', 'подружиться', 'починить', 'спеть', 'вырастить', 'вернуть', 'пригласить'] as const;
const GENTLE_SUBJECTS = ['говорящий зверёк', 'потерянный ключик', 'радуга', 'пирог', 'волшебное семечко', 'светлячки', 'загадка', 'старый мельник', 'ветер', 'облако'] as const;

export const museTag = (style: string | undefined, rng: Rng = Math.random) => {
  const gentle = style === 'fairytale';
  const a = gentle ? pick(GENTLE_ACTIONS, rng) : pick(MUSE_ACTIONS, rng);
  const s = gentle ? pick(GENTLE_SUBJECTS, rng) : pick(MUSE_SUBJECTS, rng);
  return `[MUSE: «${a} — ${s}»]`;
};

export const ACTION_CATEGORIES = ['Профильный', 'Рискованный', 'Синергия', 'Искушение'] as const;

/**
 * Слоты действий: сколько и каких категорий получит каждый герой.
 * Синергия возможна только в партии из 2+ героев; Искушение реже в сказочном стиле.
 */
export const actionSlotsTag = (names: string[], style: string | undefined, rng: Rng = Math.random) => {
  if (!names.length) return '';
  const weights: Record<string, number> = {
    'Профильный': 35, 'Рискованный': 25, 'Синергия': names.length > 1 ? 20 : 0, 'Искушение': style === 'fairytale' ? 5 : 20,
  };
  const total = Object.values(weights).reduce((a, b) => a + b, 0);
  const roll = () => {
    let r = rng() * total;
    for (const [k, w] of Object.entries(weights)) { if ((r -= w) < 0) return k; }
    return 'Профильный';
  };
  const parts = names.map(n => {
    const count = 1 + Math.floor(rng() * 3);
    const cats = Array.from({ length: count }, roll);
    return `${n}: ${cats.join(', ')}`;
  });
  return `[ACTION SLOTS: ${parts.join('; ')}]`;
};

/** Идея главы для сказки: помощник / чудо / испытание. Модель вольна взять одну. */
const TALE_HELPERS = ['мудрая черепаха', 'болтливая сорока', 'сонный дракончик', 'добрый великан', 'звёздный мотылёк', 'старушка-пряха', 'робкий гном', 'лунный заяц'] as const;
const TALE_WONDERS = ['поющий цветок', 'карта, которая рисуется сама', 'шапка-невидимка, которая чихает', 'колокольчик, зовущий ветер', 'зеркальце, показывающее правду', 'клубок-проводник'] as const;
const TALE_TRIALS = ['загадка у моста', 'спор двух королей', 'потерявшийся малыш', 'заколдованная тропинка', 'обида, которую надо простить', 'буря, которую надо переждать', 'страх, который надо победить'] as const;

export const taleIdea = (rng: Rng = Math.random) =>
  `помощник — ${pick(TALE_HELPERS, rng)}; чудо — ${pick(TALE_WONDERS, rng)}; испытание — ${pick(TALE_TRIALS, rng)}`;
