export const disclaimerFor = (audience: DisclaimerAudience) =>
  DISCLAIMER_SECTIONS.filter(s => !s.audience || s.audience.includes(audience));

/** Markdown-версия — для гайда и экспорта. */
export const disclaimerMarkdown = (audience?: DisclaimerAudience) =>
  (audience ? disclaimerFor(audience) : DISCLAIMER_SECTIONS)
    .map(s => `**${s.title}.** ${s.text}`)
    .join('\n\n');
