export const archetypeById = (id?: string) => ARCHETYPES.find(a => a.id === id);

/** Применяет стартовый набор архетипа к листу героя, который прислала модель (числа и предметы — от архетипа). */
export function applyArchetype(c: Partial<Character>, a: Archetype, genre: Genre): Partial<Character> {
  const [weapon, second] = a.gear[genre] || a.gear.fantasy;
  const equipment: EquipmentSlot[] = [
    { slot: 'main-hand', item: { name: weapon.name, description: 'Стартовое снаряжение', bonus: weapon.bonus, rarity: 'common' } },
    { slot: /защит/.test(second.bonus) ? 'body' : 'accessory', item: { name: second.name, description: 'Стартовое снаряжение', bonus: second.bonus, rarity: 'common' } },
  ];
  const signature: Ability = { name: a.ability.name, desc: a.ability.desc, effect: a.ability.bonus, type: 'mechanical', bonus: a.ability.bonus };
  const modelItems = (c.inventory || []).filter(i => typeof i === 'string').slice(0, 2) as string[];
  return {
    ...c,
    hp: `${a.hp}/${a.hp}`,
    tokens: a.tokens,
    gold: a.gold,
    archetype: a.id,
    equipment,
    inventory: [...(a.kit[genre] || a.kit.fantasy), ...modelItems.filter(i => !(a.kit[genre] || []).includes(i))].slice(0, 5),
    abilities: [signature, ...(c.abilities || []).filter(x => x.name !== signature.name)],
  };
}

/** Строка для GAME START: модель знает архетип и описывает героя под него. */
export const archetypeLine = (id?: string) => {
  const a = archetypeById(id);
  return a ? ` [архетип: ${a.name} — ${a.pitch}; фирменная способность «${a.ability.name}»: ${a.ability.desc}]` : '';
};
